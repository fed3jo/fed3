import {test,expect} from '@playwright/test';
import {seedDocuments} from '../lib/cms/seed';

// Run only against the documented loopback PostgreSQL fixture, never production.
test.skip(process.env.CMS_TEST_FIXTURE!=='1','Requires the local Supabase contract fixture.');
test('manager publishes a new app through real API and current templates; editor cannot publish',async({page,baseURL})=>{
  test.setTimeout(90000);
  expect(new URL(baseURL!).hostname).toMatch(/^(127\.0\.0\.1|localhost)$/);
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.goto('/ar/admin/');
  await page.getByLabel('البريد الإلكتروني',{exact:true}).fill('manager@example.test');
  await page.getByLabel('كلمة المرور',{exact:true}).fill('fixture-password-only');
  await page.getByRole('button',{name:'تسجيل الدخول',exact:true}).click();
  await expect(page.getByRole('heading',{name:'التطبيقات',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'استيراد التطبيقات الحالية',exact:true}).click();
  await expect(page.getByRole('button',{name:/Signal.*منشور/})).toBeVisible();
  expect((await page.request.get('/ar/alternatives/')).ok()).toBe(true);
  const fixtureDoc=structuredClone(seedDocuments[0]);
  fixtureDoc.id='fixture-new-app';fixtureDoc.name='Fixture App';fixtureDoc.sortOrder=0;
  fixtureDoc.description={ar:'تطبيق جديد منشور من لوحة الإدارة',en:'A new app published from the dashboard'};
  fixtureDoc.start.intro={ar:'شرح التطبيق الجديد داخل نفس البطاقة.',en:'New app description in the same card.'};
  fixtureDoc.introduction.description={ar:'تعريف التطبيق الجديد.',en:'The new app introduction.'};
  const save=await page.request.post('/api/admin/save/',{headers:{Origin:baseURL!},data:{document:fixtureDoc,version:null}});
  expect(save.status()).toBe(200);
  const record=(await save.json()).record;
  const publish=await page.request.post('/api/admin/publish/',{headers:{Origin:baseURL!},data:{id:fixtureDoc.id,version:record.version}});expect(publish.status()).toBe(200);
  const publicPage=await page.context().newPage();
  await publicPage.goto('/ar/alternatives/?app=fixture-new-app');
  await expect(publicPage.locator('[data-app-showcase]')).toHaveAttribute('data-active-app','fixture-new-app');
  await expect(publicPage.locator('[data-app-showcase]')).toContainText('شرح التطبيق الجديد داخل نفس البطاقة.');
  await publicPage.goto('/ar/apps/fixture-new-app/');
  await expect(publicPage.locator('h1')).toHaveText('Fixture App');
  await expect(publicPage.locator('#app-comparison')).toBeVisible();
  await publicPage.goto('/en/apps/fixture-new-app/');
  await expect(publicPage.locator('main')).toContainText(fixtureDoc.description.en);
  await page.reload();await page.getByRole('button',{name:/Fixture App.*منشور/}).click();
  await page.getByRole('button',{name:'التعريف والفوائد',exact:true}).click();
  await page.getByLabel(/^الوصف المختصر/).fill('تعديل محفوظ كمسودة فقط');
  await page.getByRole('button',{name:'حفظ المسودة',exact:true}).click();await expect(page.getByRole('status')).toContainText('حُفظت المسودة');
  await publicPage.goto('/ar/apps/fixture-new-app/');await expect(publicPage.locator('main')).toContainText(fixtureDoc.description.ar);await expect(publicPage.locator('main')).not.toContainText('تعديل محفوظ كمسودة فقط');
  const popup=page.waitForEvent('popup');await page.getByRole('button',{name:'معاينة عربي ↗',exact:true}).click();
  const preview=await popup;await preview.waitForURL('**/admin/preview/fixture-new-app/');await expect(preview.locator('main')).toContainText('تعديل محفوظ كمسودة فقط');await preview.close();
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
  await page.screenshot({path:'test-results/admin-editor-mobile.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  await page.screenshot({path:'test-results/admin-editor-desktop.png',fullPage:false});
  const exported=await page.request.get('/api/admin/export/');expect(exported.status()).toBe(200);const backup=await exported.json();expect(backup.apps).toHaveLength(6);
  const noOrigin=await page.request.post('/api/admin/seed/',{headers:{Origin:'https://untrusted.example'},data:{}});expect(noOrigin.status()).toBe(403);
  await page.getByRole('button',{name:'تسجيل الخروج',exact:true}).click();
  await page.getByLabel('البريد الإلكتروني',{exact:true}).fill('editor@example.test');await page.getByLabel('كلمة المرور',{exact:true}).fill('fixture-password-only');await page.getByRole('button',{name:'تسجيل الدخول',exact:true}).click();
  await expect(page.getByText('صلاحية محرر',{exact:true})).toBeVisible();
  const forbidden=await page.request.post('/api/admin/publish/',{headers:{Origin:baseURL!},data:{id:fixtureDoc.id,version:3}});expect(forbidden.status()).toBe(403);
  const forbiddenExport=await page.request.get('/api/admin/export/');expect(forbiddenExport.status()).toBe(403);
  await page.getByRole('button',{name:/Fixture App.*منشور/}).click();await expect(page.getByRole('button',{name:'حفظ ونشر',exact:true})).toHaveCount(0);
  await publicPage.close();
});
